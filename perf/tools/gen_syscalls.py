#!/usr/bin/env python3
"""Regenerate smbperf/syscalls_gen.py from a kernel tree's x86-64 table.

    python3 tools/gen_syscalls.py /path/to/linux > smbperf/syscalls_gen.py

raw_syscalls:sys_enter carries only the number; this names it.
"""

from __future__ import annotations

import os
import re
import sys


def main() -> None:
    tree = sys.argv[1] if len(sys.argv) > 1 else "/CODE/linux"
    path = os.path.join(tree, "arch/x86/entry/syscalls/syscall_64.tbl")
    names: dict[int, str] = {}
    with open(path) as f:
        for line in f:
            parts = line.split()
            if len(parts) < 3 or parts[0].startswith("#"):
                continue
            if parts[1] in ("common", "64"):
                names[int(parts[0])] = parts[2]
    version = ""
    try:
        with open(os.path.join(tree, "Makefile")) as f:
            head = dict(re.findall(r"^(VERSION|PATCHLEVEL) = (\d+)", f.read(),
                                   re.M))
        version = f"{head['VERSION']}.{head['PATCHLEVEL']}"
    except (OSError, KeyError):
        pass
    print('"""x86-64 system call names, generated by tools/gen_syscalls.py; do')
    print("not edit.")
    print()
    print(f"Source: Linux {version or '(unknown version)'}.")
    print('"""')
    print()
    print("SYSCALLS = {")
    for nr in sorted(names):
        print(f"    {nr}: {names[nr]!r},")
    print("}")


if __name__ == "__main__":
    main()
