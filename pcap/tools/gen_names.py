#!/usr/bin/env python3
"""Regenerate smbpcap/names_gen.py from the installed tshark's value tables.

    python3 tools/gen_names.py > smbpcap/names_gen.py

The tables are static data; regenerate when a newer tshark learns new
statuses or FSCTLs.
"""

from __future__ import annotations

import subprocess
import sys

TABLES = {
    "NT_STATUS": ("smb2.nt_status", None),
    "FSCTL": ("smb2.ioctl.function", None),
    "FILE_INFO_LEVEL": ("smb2.file_info.infolevel", "SMB2_"),
    "FS_INFO_LEVEL": ("smb2.fs_info.infolevel", None),
    "FIND_LEVEL": ("smb2.find.infolevel", "SMB2_FIND_"),
    "SMB1_CMD": ("smb.cmd", None),
    "TRANS2": ("smb.trans2.cmd", None),
    "NT_TRANSACT": ("smb.nt.function", None),
}


def main() -> None:
    out = subprocess.run(
        ["tshark", "-G", "values"], capture_output=True, text=True,
        check=True,
    ).stdout
    version = subprocess.run(
        ["tshark", "--version"], capture_output=True, text=True,
    ).stdout.splitlines()[0]
    tables: dict[str, dict[int, str]] = {name: {} for name in TABLES}
    wanted = {field: name for name, (field, _) in TABLES.items()}
    for line in out.splitlines():
        parts = line.split("\t")
        if len(parts) != 4 or parts[0] != "V" or parts[1] not in wanted:
            continue
        name = wanted[parts[1]]
        strip = TABLES[name][1]
        label = parts[3]
        if strip and label.startswith(strip):
            label = label[len(strip):]
        if name in ("SMB1_CMD", "NT_TRANSACT"):
            label = label.upper().replace(" ", "_")
        tables[name][int(parts[2], 0)] = label
    w = sys.stdout.write
    w('"""Value tables generated by tools/gen_names.py; do not edit.\n\n')
    w(f"Source: {version}\n")
    w('"""\n\n')
    for name in TABLES:
        w(f"{name} = {{\n")
        for value, label in sorted(tables[name].items()):
            w(f"    {value:#x}: {label!r},\n")
        w("}\n\n")


if __name__ == "__main__":
    main()
